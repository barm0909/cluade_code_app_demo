-- 消費税。単価 (販売定価・実売単価・原価) はこれまでどおり税抜で持ち、
-- 税率だけを商品に持たせて消費税・税込金額は計算で出す。
-- 食品は軽減税率 8%、ラベル等の資材は標準税率 10% と商品ごとに異なるため、商品単位で持つ。

-- 商品の消費税率 (%)。8 = 軽減税率 / 10 = 標準税率。
-- 既存の商品は食品在庫のアプリなので軽減税率 (8) とみなす (資材は画面から 10 に直す)。
ALTER TABLE products ADD COLUMN tax_rate INTEGER NOT NULL DEFAULT 8;

-- 売上出庫した時点の税率。商品の税率はあとから変えられるため、過去の売上の消費税が
-- 変わらないよう出庫時に写し取る (cost_unit_price と同じ考え方)。売上出庫以外では NULL。
-- この列ができる前の売上出庫も NULL で、画面では商品の現在の税率で代用した「概算」になる。
ALTER TABLE stock_transactions ADD COLUMN tax_rate INTEGER;
